/**
 * 役割: 画像の黒背景を透明にしたRGBA配列を作る。
 * 入力: RGBA順の配列、背景と見なすRGB各値の上限。
 * 出力: 元配列を変更せず、暗い画素のalphaを0にしたUint8ClampedArray。
 */
export function makeDarkPixelsTransparent(rgbaBytes, threshold) {
  const transparentPixels = new Uint8ClampedArray(rgbaBytes);
  for (let index = 0; index < transparentPixels.length; index += 4) {
    const red = transparentPixels[index];
    const green = transparentPixels[index + 1];
    const blue = transparentPixels[index + 2];
    if (red <= threshold && green <= threshold && blue <= threshold) {
      transparentPixels[index + 3] = 0;
    }
  }
  return transparentPixels;
}
